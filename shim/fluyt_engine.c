/* The bridge: Felucca's engine, in a drumlogue unit.
 *
 * One translation unit, exactly as Felucca's own firmware/src/felucca.c is one: the generated
 * tables, then core.h, dsp.c and the engine, then the parameter descriptors, the modulation matrix
 * and the voice code. Every file of Felucca's is compiled as upstream ships it; the layer around
 * them - the FM-1's UI, sequencer, MIDI, storage, mixer and effects - is what is not here. A unit
 * is one part that a keyboard plays.
 *
 * What Felucca supplies through those files, unchanged:
 *   - the engine (one eng_*.c, or all nine for the host tools/),
 *   - voice allocation, the ADSR on Felucca's tables, the LFO, glide and unison (voice.c),
 *   - the per-track modulation matrix (mod.c),
 *   - the parameter descriptors, their ranges and their formatting (params.c),
 *   - the sound of a preset and the state a track starts in (fluyt_preset.c, after ui.c:726/774).
 *
 * What this file adds, because a drumlogue unit has no FM-1 around it:
 *   - the event queue the control thread writes and Render drains (fluyt_queue.h),
 *   - the panel: which of Felucca's parameters this unit exposes (rows.def, generated from
 *     Felucca's own descriptors by tools/gen_rows.c),
 *   - the mix: level, pan and master - fx.c's mix_part and master_out for one part - and the
 *     conversion to the float the drumlogue asks for.
 *
 * The tables are generated for 48 kHz (build.sh), which is the drumlogue's rate, so Felucca's
 * envelopes, LFO, pitch, cutoff and levels keep their real times and frequencies. Three engines
 * carry a 44.1 kHz constant in their own C (NOISE's crush rate, VOICE's formant coefficients,
 * FM6's envelope table); see README.md. */

